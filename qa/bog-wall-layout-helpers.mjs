export function shortCrossing(b){return b.width<b.height?[{x:b.x-2,y:b.y+b.height/2},{x:b.x+b.width+2,y:b.y+b.height/2}]:[{x:b.x+b.width/2,y:b.y-2},{x:b.x+b.width/2,y:b.y+b.height+2}];}
